let currentLanguage = localStorage.getItem("kisan_lang") || "en";

function setLanguage(lang) {
  if (!["en", "hi", "te"].includes(lang)) {
    lang = "en";
  }
  currentLanguage = lang;
  localStorage.setItem("kisan_lang", lang);
  document.documentElement.lang = lang;

  const strings = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.en;

  // Apply translations to all DOM elements with data-i18n attribute
  document.querySelectorAll("[data-i18n]").forEach(elem => {
    const key = elem.getAttribute("data-i18n");
    if (strings[key]) {
      if (elem.tagName === "INPUT" || elem.tagName === "TEXTAREA") {
        elem.placeholder = strings[key];
      } else {
        elem.innerText = strings[key];
      }
    }
  });

  // Update language select dropdown value if present
  const langSelect = document.getElementById("languageSelect");
  if (langSelect && langSelect.value !== lang) {
    langSelect.value = lang;
  }

  // Trigger custom event so other modules (voice, results) can react
  window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
}

function getTranslation(key) {
  const strings = UI_TRANSLATIONS[currentLanguage] || UI_TRANSLATIONS.en;
  return strings[key] || key;
}

function getCurrentLanguage() {
  return currentLanguage;
}

// Export to window
window.setLanguage = setLanguage;
window.getTranslation = getTranslation;
window.getCurrentLanguage = getCurrentLanguage;
window.UI_TRANSLATIONS = UI_TRANSLATIONS;

